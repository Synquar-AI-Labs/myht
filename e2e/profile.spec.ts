import { test, expect, family, signIn, more, checked } from './helpers';

test('profile alerts update another open page; About preserves unknowns and confirmed none', async ({ page, sessions }) => {
  const f = await family();
  await signIn(page, f.admin); await more(page, 'About ');
  await expect(page.getByRole('heading', { name: 'About Synthetic recipient' })).toBeVisible();
  await expect(page.getByText('Date of birth: Not recorded')).toBeVisible();
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Date of birth', { exact: true }).fill('1960-10-22');
  await dialog.getByLabel('Fall risk', { exact: true }).selectOption('true');
  await dialog.getByLabel('Fall risk note', { exact: true }).fill('Two people to stand');
  await dialog.getByLabel('Emergency notes', { exact: true }).fill('Synthetic emergency note');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByText(/years · born Oct 22, 1960/)).toBeVisible();
  const second = await sessions(); await signIn(second, f.member);
  await expect(second.locator('[data-today-alerts]')).toContainText('Fall risk: Two people to stand');
  await page.getByRole('button', { name: 'None known: Allergies', exact: true }).click();
  await expect.poll(async () => (await checked(f.admin.client.from('care_profiles').select('none_known').eq('household_id', f.id).single())).none_known).toContain('allergy');
  await page.getByRole('button', { name: 'Clear None known: Allergies', exact: true }).click();
  await expect(page.getByRole('button', { name: 'None known: Allergies', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'None known: Allergies', exact: true }).click();
  await page.getByRole('button', { name: 'Add Allergies', exact: true }).click();
  await dialog.getByLabel('Allergies', { exact: true }).fill('Synthetic latex allergy');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(second.locator('[data-today-alerts]')).toContainText('Allergic to Synthetic latex allergy');
  expect((await checked(f.admin.client.from('care_profiles').select('none_known').eq('household_id', f.id).single())).none_known).not.toContain('allergy');
  await second.locator('[data-today-alerts]').click();
  await expect(second.getByRole('heading', { name: 'About Synthetic recipient' })).toBeVisible();
  await second.getByRole('button', { name: 'Emergency card', exact: true }).click();
  const card = second.locator('[data-emergency-card]');
  await expect(card).toContainText('Synthetic latex allergy');
  await expect(card).toContainText('Not recorded');
  await expect(card).toContainText('Synthetic emergency note');
  await expect(card).toContainText('Made ');
  const download = second.waitForEvent('download');
  await second.getByRole('button', { name: 'Save or share PDF' }).click();
  const pdf = await download;
  expect(pdf.suggestedFilename()).toBe('emergency-card.pdf');
  await pdf.saveAs('test-results/profile/emergency-card.pdf');
  await page.getByRole('button', { name: 'Synthetic latex allergy', exact: true }).click();
  await expect(page.getByRole('alertdialog')).toContainText('Remove this alert?');
  await page.getByRole('alertdialog').getByRole('button', { name: 'Keep it' }).click();
  await expect(page.getByRole('button', { name: 'Synthetic latex allergy', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Synthetic latex allergy', exact: true }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Remove', exact: true }).click();
  await expect.poll(async () => await checked(f.admin.client.from('care_alerts').select('id').eq('household_id', f.id))).toHaveLength(0);
});

test('contacts have native links, edit/delete work, and a failed source cannot make an emergency card', async ({ page, sessions }) => {
  void sessions;
  const f = await family(); await signIn(page, f.admin); await more(page, 'Contacts');
  await page.getByRole('button', { name: 'Add', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Name', { exact: true }).fill('Synthetic contact');
  await dialog.getByLabel('Role', { exact: true }).fill('First to call');
  await dialog.getByLabel('Phone', { exact: true }).fill('+1 (555) 010-1234');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Call Synthetic contact', exact: true })).toHaveAttribute('href', 'tel:+15550101234');
  await expect(page.getByRole('link', { name: 'Text Synthetic contact', exact: true })).toHaveAttribute('href', 'sms:+15550101234');
  await expect(page.getByText('+1 (555) 010-1234', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit Synthetic contact' }).click();
  await dialog.getByLabel('Role', { exact: true }).fill('Updated role');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByText('Updated role', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Delete', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Edit Synthetic contact' }).click();
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(page.getByText('Synthetic contact', { exact: true })).toHaveCount(0);
  expect(await checked(f.admin.client.from('contacts').select('id').eq('household_id', f.id))).toHaveLength(0);
  // Remount queries with a real failed source; no partial card or PDF is offered.
  await page.route('**/rest/v1/contacts?**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Synthetic offline' }) }));
  await page.reload(); await more(page, 'About ');
  await page.getByRole('button', { name: 'Emergency card', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText("Couldn't load this information");
  await expect(page.locator('[data-emergency-card]')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Save or share PDF' })).toHaveCount(0);
  await page.unroute('**/rest/v1/contacts?**');
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await expect(page.locator('[data-emergency-card]')).toBeVisible();
  await page.getByRole('button', { name: 'Today', exact: true }).click();
  await page.route('**/rest/v1/care_alerts?**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Synthetic offline' }) }));
  await page.reload();
  await expect(page.getByText('Alerts could not load ·')).toBeVisible();
  await page.unroute('**/rest/v1/care_alerts?**');
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await expect(page.getByText('Alerts could not load ·')).toHaveCount(0);
});
