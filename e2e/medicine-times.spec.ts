import { test, expect, family, checked, signIn, today, choose, more } from './helpers';

test('k. Medicine form times, filler replacement, read-back, Other and legacy values', async ({ page, sessions }) => {
  void sessions;
  const f = await family();
  const legacy = await checked(f.admin.client.from('medicines').insert({ household_id: f.id, name: 'Legacy typed medicine', schedule_time: '9:10AM / with food', frequency: 'on clinic days', med_type: 'Custom old type', schedule_note: 'Keep this note' }).select().single());
  await signIn(page, f.admin);
  await more(page, 'Medicine cabinet');
  await page.getByRole('button', { name: 'Add', exact: true }).click();
  const form = page.getByRole('dialog');
  await form.getByPlaceholder('Medicine name').fill('Round medicine');
  await expect(form.getByRole('status')).toHaveText('Given every day. No times set, so it will not appear under Coming up.');
  await form.getByRole('button', { name: 'Add another time' }).click();
  await form.getByRole('combobox', { name: 'Medicine time 1', exact: true }).click();
  await expect(page.getByRole('option', { name: '8:00 AM', exact: true })).toBeFocused();
  await page.getByRole('option', { name: '6:00 AM', exact: true }).click();
  await form.getByRole('button', { name: 'Add another time' }).click();
  await choose(page, form.getByRole('combobox', { name: 'Medicine time 2', exact: true }), '10:00 AM');
  await expect(form.getByRole('status')).toHaveText('Given every day at 6:00 AM and 10:00 AM.');
  await form.getByRole('combobox', { name: 'Medicine time 2', exact: true }).click();
  await expect(page.getByRole('option', { name: '6:00 AM', exact: true })).toBeDisabled();
  await page.keyboard.press('Escape');
  await form.getByRole('button', { name: 'Given every few hours? Fill the times in for me.' }).click();
  await form.getByRole('button', { name: 'Fill times', exact: true }).click();
  await expect(form.getByText('Replace the times you picked?', { exact: true })).toBeVisible();
  await form.getByRole('button', { name: 'Keep my times' }).click();
  await expect(form.getByRole('combobox', { name: /^Medicine time/ })).toHaveCount(2);
  await form.getByRole('button', { name: 'Fill times', exact: true }).click();
  await form.getByRole('button', { name: 'Replace times', exact: true }).click();
  await expect(form.getByRole('combobox', { name: /^Medicine time/ })).toHaveCount(6);
  await choose(page, form.getByRole('combobox', { name: 'Every how many hours' }), '1 hour');
  await form.getByRole('button', { name: 'Fill times', exact: true }).click();
  await form.getByRole('button', { name: 'Replace times', exact: true }).click();
  await expect(form.getByRole('combobox', { name: /^Medicine time/ })).toHaveCount(24);
  await expect(form.getByRole('button', { name: 'Add another time' })).toBeDisabled();
  await choose(page, form.getByRole('combobox', { name: 'Every how many hours' }), '4 hours');
  await form.getByRole('button', { name: 'Fill times', exact: true }).click();
  await form.getByRole('button', { name: 'Replace times', exact: true }).click();
  await expect(form.getByRole('status')).toHaveText('Given every day at 12:00 AM, 4:00 AM, 8:00 AM, 12:00 PM, 4:00 PM and 8:00 PM.');
  await choose(page, form.getByRole('combobox', { name: 'Type', exact: true }), 'Other');
  await form.getByLabel('What kind of medicine is it?').fill('Support medicine');
  await form.getByRole('button', { name: 'Add Medicine', exact: true }).click();
  await expect(form).toHaveCount(0);
  const medicine = await checked(f.admin.client.from('medicines').select('*').eq('name', 'Round medicine').single());
  expect(medicine.schedule_time).toBe('12:00 AM / 4:00 AM / 8:00 AM / 12:00 PM / 4:00 PM / 8:00 PM');
  expect(medicine.frequency).toBe('daily'); expect(medicine.med_type).toBe('Support medicine');
  await page.getByRole('button', { name: 'Edit Round medicine', exact: true }).click();
  await choose(page, form.getByRole('combobox', { name: 'Which days is it given?' }), 'Every 3 days');
  await expect(form.getByLabel('Which day does it start?')).toHaveValue(today());
  await form.getByLabel('Which day does it start?').fill('');
  await form.getByRole('button', { name: 'Given every few hours? Fill the times in for me.' }).click();
  await form.getByRole('button', { name: 'Fill times', exact: true }).click();
  await form.getByRole('button', { name: 'Replace times', exact: true }).click();
  await expect(form.getByRole('combobox', { name: 'Which days is it given?' })).toHaveText('Every 3 days');
  await expect(form.getByRole('status')).toContainText('Pick a start day to see this under Coming up.');
  await form.getByRole('button', { name: 'Save Changes' }).click();
  await expect(form).toHaveCount(0);
  await page.getByRole('button', { name: 'Today', exact: true }).click();
  const upcoming = page.locator('section').filter({ hasText: 'Coming up · next 12 hours' });
  await expect(upcoming.getByText('Nothing scheduled in the next 12 hours.')).toBeVisible();
  await more(page, 'Medicine cabinet');
  await page.getByRole('button', { name: 'Edit Legacy typed medicine', exact: true }).click();
  await expect(form.getByRole('combobox', { name: 'Medicine time 1' })).toHaveText('9:10 AM (earlier entry)');
  await expect(form.getByRole('combobox', { name: 'Which days is it given?' })).toHaveText('on clinic days');
  await expect(form.getByRole('combobox', { name: 'Type', exact: true })).toHaveText('Other');
  await expect(form.getByLabel('What kind of medicine is it?')).toHaveValue('Custom old type');
  await expect(form.getByRole('status')).toHaveText('Given on clinic days at 9:10 AM.');
  await expect(form.getByText('Earlier entry: 9:10AM / with food', { exact: true })).toBeVisible();
  await form.getByRole('button', { name: 'Save Changes' }).click();
  await expect(form).toHaveCount(0);
  const saved = await checked(f.admin.client.from('medicines').select('*').eq('id', legacy.id).single());
  expect(saved.schedule_time).toBe('9:10 AM');
  expect(saved.frequency).toBe('on clinic days');
  expect(saved.schedule_note).toBe('Keep this note\nEarlier entry: 9:10AM / with food');
  const member = f.people.find(person => person.user_id === f.member.id)!;
  const dose = await checked(f.member.client.from('medicine_logs').insert({ household_id: f.id, medicine_id: legacy.id, date: today(), hour: 9, minute: 10, am_pm: 'AM', caregiver_id: member.caregiver_id, recorded_by: member.display_name }).select().single());
  await page.getByRole('button', { name: 'History', exact: true }).click();
  await page.getByRole('button', { name: 'Edit this day' }).click();
  const row = page.getByText(/9:10 AM[\s\S]*by Member person/).locator('../..');
  await row.getByRole('button').first().click();
  await expect(page.getByRole('combobox', { name: 'Dose time' })).toHaveText('9:10 AM (earlier entry)');
  await page.getByRole('button', { name: 'Update', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Update', exact: true })).toHaveCount(0);
  await expect.poll(async () => (await checked(f.member.client.from('medicine_logs').select('minute').eq('id', dose.id).single())).minute).toBe(10);
});

test('l. Grouped Today times, quarter-hour dose sync and closed charts on phone/tablet', async ({ page, sessions }) => {
  const f = await family();
  for (const [name, time] of [['Quarter medicine A', '12:15 PM'], ['Quarter medicine B', '12:15 PM'], ['Later medicine', '2:15 PM']]) {
    await checked(f.admin.client.from('medicines').insert({ household_id: f.id, name, frequency: 'daily', schedule_time: time }));
  }
  const fixed = new Date(`${today()}T12:15:00-04:00`);
  await page.clock.setFixedTime(fixed);
  await signIn(page, f.admin);
  const upcoming = page.locator('section').filter({ hasText: 'Coming up · next 12 hours' });
  await expect(upcoming.getByRole('button', { name: /12:15 PM.*2 medicines/ })).toHaveAttribute('aria-expanded', 'true');
  await expect(upcoming.getByRole('button', { name: /2:15 PM.*1 medicine/ })).toHaveAttribute('aria-expanded', 'false');
  await upcoming.getByRole('button', { name: /^Quarter medicine A/ }).click();
  await page.getByRole('button', { name: 'Change', exact: true }).click();
  await choose(page, page.getByRole('combobox', { name: 'Dose time' }), '12:15 PM');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect.poll(async () => (await checked(f.admin.client.from('medicine_logs').select('minute').eq('household_id', f.id)))[0]?.minute).toBe(15);
  const second = await sessions();
  await second.clock.setFixedTime(fixed);
  await signIn(second, f.member);
  const given = second.locator('section').filter({ hasText: 'Given · last 12 hours' });
  const timeRow = given.getByRole('button', { name: /12:15 PM.*1 given/ });
  await expect(timeRow).toHaveAttribute('aria-expanded', 'false');
  await timeRow.click();
  await expect(given.getByRole('button', { name: /^Quarter medicine A/ })).toBeVisible();
  for (const viewport of [{ width: 393, height: 852 }, { width: 820, height: 1180 }]) {
    await page.setViewportSize(viewport);
    const charts = page.getByRole('button', { name: /^Visuals & trends/ });
    await expect(charts).toHaveAttribute('aria-expanded', 'false');
    await charts.click();
    await expect(charts).toHaveAttribute('aria-expanded', 'true');
    await expect(page.getByRole('button', { name: /More charts/ })).toBeVisible();
    await charts.click();
  }
});
