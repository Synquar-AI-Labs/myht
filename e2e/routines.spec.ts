import { test, expect, family, signIn, more, checked, today, tomorrow } from './helpers';

test('routine plans add, change times tomorrow, stop, delete and protect recorded items', async ({ page, sessions }) => {
  void sessions;
  const f = await family(); await signIn(page, f.admin); await more(page, 'Meals & exercise');
  await page.getByRole('button', { name: 'Add meal', exact: true }).click();
  await page.getByLabel('Meal name', { exact: true }).fill('Synthetic breakfast');
  await page.getByLabel('Food', { exact: true }).fill('Synthetic oatmeal');
  await page.getByLabel('Drink', { exact: true }).fill('Water');
  await page.getByRole('button', { name: '+ Add a time', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Plan time 1' })).toContainText('8:00 AM');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.locator('[data-routine-form]')).toHaveCount(0);
  await expect.poll(async () => (await checked(f.admin.client.from('routine_items').select('*').eq('household_id', f.id))).length).toBe(1);
  const first = (await checked(f.admin.client.from('routine_items').select('*').eq('household_id', f.id)))[0];
  await page.getByRole('button', { name: /8:00 AM Synthetic breakfast/ }).click();
  await page.getByRole('combobox', { name: 'Plan time 1' }).click();
  await page.getByRole('option', { name: '9:00 AM', exact: true }).click();
  await expect(page.getByText('New times start tomorrow', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.locator('[data-routine-form]')).toHaveCount(0);
  await expect(page.getByRole('button', { name: /8:00 AM Synthetic breakfast/ })).toBeVisible();
  let saved = (await checked(f.admin.client.from('routine_items').select('*').eq('id', first.id).single()));
  expect(saved.previous_schedule_time).toBe('8:00 AM'); expect(saved.schedule_time).toBe('9:00 AM'); expect(saved.schedule_from).toBe(tomorrow());
  // A second edit today retains the original effective times.
  await page.getByRole('button', { name: /8:00 AM Synthetic breakfast/ }).click();
  await page.getByRole('combobox', { name: 'Plan time 1' }).click(); await page.getByRole('option', { name: '10:00 AM', exact: true }).click();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.locator('[data-routine-form]')).toHaveCount(0);
  saved = await checked(f.admin.client.from('routine_items').select('*').eq('id', first.id).single());
  expect(saved.previous_schedule_time).toBe('8:00 AM'); expect(saved.schedule_time).toBe('10:00 AM');
  await checked(f.admin.client.from('routine_logs').insert({ household_id: f.id, item_id: first.id, caregiver_id: f.people[0].caregiver_id, for_date: today(), for_minute: 480, done_at: new Date().toISOString(), recorded_by: f.people[0].display_name, kind: 'meal', name: first.name, details: first.details, drink: first.drink, amount: 'most' }));
  await page.getByRole('button', { name: /8:00 AM Synthetic breakfast/ }).click();
  await expect(page.getByText('This item has records. It can be stopped, not deleted.')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Delete', exact: true })).toHaveCount(0);
  const refused = await f.admin.client.from('routine_items').delete().eq('id', first.id); expect(refused.error?.code).toBe('23503');
  await page.getByRole('button', { name: 'Stop from a date' }).click();
  await page.getByLabel('Stop from', { exact: true }).fill(tomorrow());
  await page.getByRole('button', { name: 'Save stop date' }).click();
  await expect(page.locator('[data-routine-form]')).toHaveCount(0);
  expect((await checked(f.admin.client.from('routine_items').select('*').eq('id', first.id).single())).end_date).toBe(tomorrow());
  await page.getByRole('button', { name: 'Add exercise', exact: true }).click();
  await page.getByRole('button', { name: 'Knees', exact: true }).click();
  await page.getByRole('button', { name: 'Straight leg raises', exact: true }).click();
  await page.getByRole('button', { name: '+ Add a time', exact: true }).click();
  await page.getByRole('button', { name: 'More minutes' }).click();
  await page.getByRole('button', { name: '+ Add a time', exact: true }).click();
  await page.getByLabel('How to do it (optional)').fill('Synthetic note');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('button', { name: /8:00 AM Straight leg raises/ })).toBeVisible();
  await expect(page.getByRole('button', { name: /8:15 AM Straight leg raises/ })).toBeVisible();
  const exercise = (await checked(f.admin.client.from('routine_items').select('*').eq('household_id', f.id).eq('kind', 'exercise')))[0];
  expect(exercise.target_minutes).toBe(11); expect(exercise.area).toBe('Knees'); expect(exercise.move_type).toBe('Strengthen');
  await page.getByRole('button', { name: /8:00 AM Straight leg raises/ }).click();
  await page.getByRole('button', { name: 'Delete', exact: true }).click(); await page.getByRole('alertdialog').getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(page.locator('[data-routine-form]')).toHaveCount(0);
  await expect(page.getByRole('button', { name: /Straight leg raises/ })).toHaveCount(0);
  expect(await checked(f.admin.client.from('routine_items').select('id').eq('id', exercise.id))).toHaveLength(0);
});

test('typical meals are one complete insert with Undo, and diet cautions link to About', async ({ page, sessions }) => {
  void sessions;
  const f = await family(); await checked(f.admin.client.from('care_alerts').insert({ household_id: f.id, kind: 'diet', text: 'Synthetic diet caution' }));
  await signIn(page, f.admin); await more(page, 'Meals & exercise');
  await page.getByRole('button', { name: 'Start from a typical day' }).click();
  await expect(page.getByRole('status')).toContainText('6 meals filled in');
  const meals = await checked(f.admin.client.from('routine_items').select('*').eq('household_id', f.id).order('schedule_time'));
  expect(meals).toHaveLength(6); expect(meals.find(m => m.name === 'Breakfast')?.drink).toBe('Tea or water');
  await expect(page.getByRole('button', { name: 'Start from a typical day' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Start from a typical day' })).toBeVisible();
  expect(await checked(f.admin.client.from('routine_items').select('*').eq('household_id', f.id))).toHaveLength(0);
  await expect(page.getByText('Synthetic diet caution', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Open About' }).click();
  await expect(page.getByRole('heading', { name: 'About Synthetic recipient' })).toBeVisible();
});
