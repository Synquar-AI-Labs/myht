import { useEffect } from 'react';
import { useQueryClient } from '@tanstack/react-query';
import { supabase } from '@/integrations/supabase/client';
import { createInvalidationBatcher } from '@/lib/invalidationBatcher';
import { useHousehold } from '@/hooks/HouseholdProvider';
import { medicineKeys } from '@/hooks/useMedicines';
import { healthKeys } from '@/hooks/useHealthRecords';
import { domainKeys } from '@/lib/domainKeys';
import { skipKeys } from '@/hooks/useDoseSkips';
import { reconcileSequence } from '@/lib/syncSequence';

let connectionCounter = 0;

/**
 * Only the household ticker is published; medical rows never travel over
 * realtime. Mount once and refresh the affected domain through its queries.
 */
export function useRealtimeSync() {
  const queryClient = useQueryClient();
  const { householdId, refresh } = useHousehold();

  useEffect(() => {
    if (!householdId) return;
    let channel: ReturnType<typeof supabase.channel> | undefined;
    let disposed = false;
    let sequence: number | null = null;
    let reading = false;
    let retryDelay = 1000;
    let repairTimer: ReturnType<typeof setTimeout> | undefined;
    let silentTimer: ReturnType<typeof setTimeout> | undefined;
    let silentSequence: number | null = null;
    let readController: AbortController | undefined;
    const batcher = createInvalidationBatcher(queryKey => {
      if (queryKey[0] === 'household-refresh') {
        void refresh();
        return;
      }
      void queryClient.invalidateQueries({ queryKey });
    });
    const queueRefresh = () => {
      batcher.queue(['household-refresh']);
      batcher.queue([...domainKeys.invites(householdId)]);
    };
    const refreshAll = () => {
      batcher.queue(['household', householdId]);
      queueRefresh();
    };
    const repair = () => {
      if (disposed || repairTimer) return;
      const old = channel;
      channel = undefined; // Ignore CLOSED generated by our own removal.
      if (old) void supabase.removeChannel(old);
      repairTimer = setTimeout(() => {
        repairTimer = undefined;
        connect();
      }, retryDelay);
      retryDelay = Math.min(retryDelay * 2, 60_000);
    };
    const askTicker = async () => {
      if (disposed || reading) return;
      reading = true;
      const controller = new AbortController();
      readController = controller;
      const timeout = setTimeout(() => controller.abort(), 20_000);
      try {
        const { data, error } = await supabase.from('household_sync').select('seq').eq('household_id', householdId).abortSignal(controller.signal).maybeSingle();
        if (disposed || error) return;
        // No row yet means this family has not changed yet.
        const result = reconcileSequence(sequence, data?.seq ?? 0, 'read');
        sequence = result.seq;
        if (result.action === 'all') {
          refreshAll();
          silentSequence = result.seq;
          if (!silentTimer) silentTimer = setTimeout(() => { silentTimer = undefined; repair(); }, 3000);
        }
      } catch { /* A failed read never changes the remembered ticker. */ }
      finally { clearTimeout(timeout); reading = false; }
    };
    const connect = () => {
      if (disposed) return;
      const current = supabase.channel(`household-sync-${householdId}-${++connectionCounter}`);
      channel = current;
      current.on('postgres_changes',
      { event: '*', schema: 'public', table: 'household_sync', filter: `household_id=eq.${householdId}` },
      payload => {
        if (disposed || channel !== current) return;
        const next = (payload.new as { seq?: number }).seq;
        if (typeof next !== 'number') return;
        if (silentSequence !== null && next >= silentSequence) {
          clearTimeout(silentTimer);
          silentTimer = undefined;
          silentSequence = null;
        }
        const result = reconcileSequence(sequence, next, 'event');
        sequence = result.seq;
        if (result.action === 'none') return;
        if (result.action === 'all') { refreshAll(); return; }
        const table = (payload.new as { table_name?: string }).table_name;
        if (['households', 'household_members', 'caregivers', 'household_invites'].includes(table ?? '')) {
          queueRefresh();
        }
        const keys = {
          care_profiles: [domainKeys.profile(householdId)],
          routine_items: [domainKeys.routines(householdId)],
          routine_logs: [domainKeys.routineLogs(householdId)],
          care_alerts: [domainKeys.alerts(householdId)],
          contacts: [domainKeys.contacts(householdId)],
          household_invites: [domainKeys.invites(householdId)],
          medicines: [medicineKeys.list(householdId)],
          medicine_logs: [medicineKeys.logs(householdId), medicineKeys.reports(householdId)],
          dose_skips: [skipKeys(householdId)],
          health_records: [healthKeys.records(householdId)],
          bp_readings: [healthKeys.bp(householdId)],
          appointments: [domainKeys.appointments(householdId)],
          hospital_stays: [domainKeys.stays(householdId), domainKeys.staysSummary(householdId)],
          written_notes: [domainKeys.notes(householdId)],
          custom_actions: [domainKeys.actions(householdId)],
          custom_action_logs: [domainKeys.actionLogs(householdId)],
          audio_transcripts: [domainKeys.transcripts(householdId), domainKeys.transcriptCount(householdId)],
        }[table ?? ''] ?? [];
        keys.forEach(queryKey => batcher.queue([...queryKey]));
      });

      current.subscribe(status => {
        if (disposed || channel !== current) return;
        if (status === 'SUBSCRIBED') { retryDelay = 1000; void askTicker(); }
        else if (['CLOSED', 'CHANNEL_ERROR', 'TIMED_OUT'].includes(status)) repair();
      });
    };
    connect();
    void askTicker();

    const refreshVisible = () => {
      if (document.visibilityState === 'visible') { queueRefresh(); void askTicker(); }
    };
    document.addEventListener('visibilitychange', refreshVisible);
    const online = () => { void askTicker(); };
    window.addEventListener('online', online);
    const interval = setInterval(() => { if (document.visibilityState === 'visible') void askTicker(); }, 30_000);
    const familyInterval = setInterval(() => { if (document.visibilityState === 'visible') queueRefresh(); }, 5 * 60_000);

    return () => {
      disposed = true;
      readController?.abort();
      clearTimeout(repairTimer);
      clearTimeout(silentTimer);
      batcher.cancel();
      document.removeEventListener('visibilitychange', refreshVisible);
      clearInterval(interval);
      clearInterval(familyInterval);
      window.removeEventListener('online', online);
      if (channel) void supabase.removeChannel(channel);
    };
  }, [queryClient, householdId, refresh]);
}
